/* a から見た b の関係。a・b は SHUKU27 の添字 */
function sankuRelation(a, b) {
  const dist = ((b - a) % 27 + 27) % 27;
  const group = Math.floor(dist / 9);
  const inGroup = dist % 9;
  const name = inGroup === 0 ? SANKU_HEAD[group] : SANKU_IN_GROUP[inGroup - 1];
  return {
    name,
    pair: SANKU_PAIR[name],
    distance: SANKU_DISTANCE[group],
    steps: dist,
    text: SANKU_TEXT[name],
  };
}

/* 二人ぶん。向きによって関係名が変わるのが宿曜の特徴なので両方返す */
function sukuyoPair(aIndex, bIndex) {
  return {
    aToB: sankuRelation(aIndex, bIndex),
    bToA: sankuRelation(bIndex, aIndex),
  };
}
