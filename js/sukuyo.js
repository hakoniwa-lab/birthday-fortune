/* ---------- 本命宿 ---------- */

/* 旧暦の表から。既定の方式 */
function honmeiShukuByLunar(y, m, d) {
  const l = lunarDate(y, m, d);
  if (!l) return null;
  const idx = (SHUKU_MONTH_BASE[l.num - 1] + l.day - 1) % 27;
  return { index: idx, name: SHUKU27[idx][0], yomi: SHUKU27[idx][1], lunar: l };
}

/* ラヒリのアヤナムシャ(歳差の補正)。2000年1月1日を23.8531度、年あたり50.29秒で進める近似 */
function ayanamsha(jd) {
  const year = 2000 + (jd - 2451545.0) / 365.25;
  return 23.8531 + (year - 2000) * 0.0139694;
}

/* 実際の月の位置から。時刻が分からないときは正午で見る */
function honmeiShukuByMoon(y, m, d, hour, minute) {
  const hasTime = hour !== null && hour !== undefined && hour !== "";
  const jd = jdFromJst(y, m, d, hasTime ? Number(hour) : 12, hasTime ? Number(minute || 0) : 0);
  const sidereal = norm360(moonLongitude(ttFrom(jd)) - ayanamsha(jd));
  /* ナクシャトラは婁(アシュヴィニー)から始まる。SHUKU27 は昴から始まるので25ずらす */
  const nak = Math.floor(sidereal / (360 / 27));
  const idx = (nak + 25) % 27;
  return { index: idx, name: SHUKU27[idx][0], yomi: SHUKU27[idx][1], degree: sidereal, nakshatra: nak, estimated: !hasTime };
}

function sukuyoOf(y, m, d, hour, minute) {
  const byLunar = honmeiShukuByLunar(y, m, d);
  const byMoon = honmeiShukuByMoon(y, m, d, hour, minute);
  return { main: byLunar, moon: byMoon, agree: byLunar && byLunar.index === byMoon.index };
}

