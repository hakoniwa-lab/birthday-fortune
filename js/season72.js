/* 立春から並べた二十四節気の名前。候の番号を3で割ると節気が出る */
const KO72_SEKKI = ["立春", "雨水", "啓蟄", "春分", "清明", "穀雨", "立夏", "小満", "芒種",
  "夏至", "小暑", "大暑", "立秋", "処暑", "白露", "秋分", "寒露", "霜降", "立冬", "小雪",
  "大雪", "冬至", "小寒", "大寒"];
const KO72_PART = ["初候", "次候", "末候"];

/* 太陽の黄経が target になる瞬間を、jdA〜jdB の間で二分法で探す */
function _sunLonCross(jdA, jdB, target) {
  const f = (jd) => {
    let v = norm360(sunLongitude(ttFrom(jd)) - target);
    if (v > 180) v -= 360;
    return v;
  };
  let lo = jdA, hi = jdB;
  for (let i = 0; i < 50; i++) {
    const mid = (lo + hi) / 2;
    if (f(mid) < 0) lo = mid; else hi = mid;
  }
  return (lo + hi) / 2;
}

/*
 * 区切り方は2つある。1950〜2050年で数えると、次候・末候の17.8%(4,849回中864回)で日付が1日ずれる。
 *   黄経(既定) … 太陽の黄経5度ごと。雑節の半夏生(黄経100度)と同じ定義
 *   日数       … 節気の日から5日後・10日後
 * 2026年の公開カレンダーでも両方が使われている(白露次候が9/13の暦と9/12の暦がある)。
 */
const KO72_SETTINGS = { byDays: false };
function setKo72Mode(byDays) {
  KO72_SETTINGS.byDays = !!byDays;
}

const _ko72Cache = new Map();

/* その年(1月1日〜12月31日)に始まる候の一覧 */
function ko72OfYear(year) {
  const cacheKey = year + "|" + (KO72_SETTINGS.byDays ? "d" : "l");
  if (_ko72Cache.has(cacheKey)) return _ko72Cache.get(cacheKey);
  /* 前年の冬至から翌年の小寒までの節気を、時刻つきで並べる */
  const terms = [];
  for (const yy of [year - 1, year, year + 1]) {
    for (const [name, lon, month] of SEKKI24) {
      terms.push({ name, lon, jd: solarTermJd(yy, month, lon) });
    }
  }
  terms.sort((a, b) => a.jd - b.jd);

  const start = jdn(year, 1, 1), end = jdn(year, 12, 31);
  const out = [];
  for (let i = 0; i < terms.length - 1; i++) {
    const t = terms[i], next = terms[i + 1];
    const tp = jdToJstParts(t.jd);
    const termDayIdx = jdn(tp.y, tp.m, tp.d);
    for (let k = 0; k < 3; k++) {
      const lon = norm360(t.lon + 5 * k);
      let dayIdx, jd;
      if (KO72_SETTINGS.byDays) {
        dayIdx = termDayIdx + 5 * k;
        jd = t.jd + 5 * k;
      } else {
        jd = k === 0 ? t.jd : _sunLonCross(t.jd, next.jd, lon);
        const p = jdToJstParts(jd);
        dayIdx = jdn(p.y, p.m, p.d);
      }
      if (dayIdx < start || dayIdx > end) continue;
      const idx = Math.round(norm360(lon - 315) / 5) % 72;
      const dt = _ko72DayToDate(dayIdx);
      out.push({
        idx, no: idx + 1,
        name: KO72[idx][0], yomi: KO72[idx][1], meaning: KO72[idx][2],
        sekki: KO72_SEKKI[Math.floor(idx / 3)], part: KO72_PART[idx % 3],
        lon, jd, dayIdx, y: dt.y, m: dt.m, d: dt.d,
      });
    }
  }
  out.sort((a, b) => a.dayIdx - b.dayIdx || a.lon - b.lon);
  _ko72Cache.set(cacheKey, out);
  return out;
}

function _ko72DayToDate(j) {
  const a = j + 32044, b = Math.floor((4 * a + 3) / 146097), c = a - Math.floor(146097 * b / 4);
  const dd = Math.floor((4 * c + 3) / 1461), e = c - Math.floor(1461 * dd / 4), mm = Math.floor((5 * e + 2) / 153);
  return { y: 100 * b + dd - 4800 + Math.floor(mm / 10), m: mm + 3 - 12 * Math.floor(mm / 10), d: e - Math.floor((153 * mm + 2) / 5) + 1 };
}

/* その日に始まる候(なければ null) */
function ko72StartOn(y, dayIdx) {
  return ko72OfYear(y).find((k) => k.dayIdx === dayIdx) || null;
}

/* その日が属している候 */
function ko72On(y, m, d) {
  const target = jdn(y, m, d);
  const list = [...ko72OfYear(y - 1), ...ko72OfYear(y)];
  let hit = null;
  for (const k of list) if (k.dayIdx <= target) hit = k;
  return hit;
}
