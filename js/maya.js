/* グッドマン・マルティネス・トンプソン相関。長期暦の起点 0.0.0.0.0 のユリウス日 */
const MAYA_CORRELATION = 584283;

function mayaLongCount(y, m, d) {
  const L = jdn(y, m, d) - MAYA_CORRELATION;
  const baktun = Math.floor(L / 144000);
  let r = L - baktun * 144000;
  const katun = Math.floor(r / 7200); r -= katun * 7200;
  const tun = Math.floor(r / 360); r -= tun * 360;
  const uinal = Math.floor(r / 20);
  const kin = r - uinal * 20;
  return { days: L, baktun, katun, tun, uinal, kin, text: `${baktun}.${katun}.${tun}.${uinal}.${kin}` };
}

function classicMayaOf(y, m, d) {
  const L = jdn(y, m, d) - MAYA_CORRELATION;
  /* 起点は 4アハウ 8クムク */
  const tzNum = ((L + 3) % 13 + 13) % 13 + 1;
  const tzIdx = ((L + 19) % 20 + 20) % 20;
  const haabPos = ((L + 348) % 365 + 365) % 365;
  const haabMonth = Math.floor(haabPos / 20);
  const haabDay = haabPos % 20;
  /* ツォルキンの通し番号(1〜260)。長期暦の起点は 4アハウ＝160番目 */
  const tzOrder = ((L + 159) % 260 + 260) % 260 + 1;
  return {
    longCount: mayaLongCount(y, m, d),
    tzolkin: { num: tzNum, name: TZOLKIN_DAY[tzIdx][0], latin: TZOLKIN_DAY[tzIdx][1], order: tzOrder },
    haab: { day: haabDay, month: HAAB_MONTH[haabMonth] },
    text: `${tzNum}${TZOLKIN_DAY[tzIdx][0]} ${haabDay}${HAAB_MONTH[haabMonth]}`,
  };
}

/* ユリウス日番号から暦日に戻す */
function jdnToDate(j) {
  const a = j + 32044;
  const b = Math.floor((4 * a + 3) / 146097);
  const c = a - Math.floor(146097 * b / 4);
  const dd = Math.floor((4 * c + 3) / 1461);
  const e = c - Math.floor(1461 * dd / 4);
  const mm = Math.floor((5 * e + 2) / 153);
  return {
    y: 100 * b + dd - 4800 + Math.floor(mm / 10),
    m: mm + 3 - 12 * Math.floor(mm / 10),
    d: e - Math.floor((153 * mm + 2) / 5) + 1,
  };
}

/* 同じツォルキンとハアブの組が戻ってくるまで52年(18,980日)。次に巡ってくる日を出す */
function calendarRoundNext(y, m, d, fromJdn) {
  let t = jdn(y, m, d);
  while (t <= fromJdn) t += 18980;
  return jdnToDate(t);
}

/* 自分のKINが次にめぐってくる日。260日周期だが、2月29日をまたぐと261日になるので
   1日ずつ数える(最大で1年ぶん見れば必ず見つかる) */
function nextKinDate(targetKin, fromY, fromM, fromD) {
  const start = jdn(fromY, fromM, fromD);
  for (let i = 1; i <= 400; i++) {
    const dt = jdnToDate(start + i);
    if (dreamspellKin(dt.y, dt.m, dt.d) === targetKin) return dt;
  }
  return null;
}

/* 基準日からその日までに通り過ぎたうるう日の数。ドリームスペルが伝統マヤから
   何日ぶん離れたかがそのまま出る */
function dreamspellDrift(y, m, d) {
  return leapDaysBefore(y, m, d) - leapDaysBefore(1987, 7, 26);
}

function mayaOf(y, m, d) {
  return { dreamspell: dreamspellOf(y, m, d), classic: classicMayaOf(y, m, d) };
}
