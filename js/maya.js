/*
 * 紋章どうしの関係。ドリームスペルでは紋章番号(1〜20)の足し算・引き算で決まる。
 *   同じ … 20日に一度めぐる自分の紋章の日
 *   類似 … 番号の和が19（赤い龍1と白い鏡18 など）
 *   反対 … 番号の差が10（赤い龍1と青い猿11 など）
 *   神秘 … 番号の和が21（赤い龍1と黄色い太陽20 など）
 * 4つは同時に成立しないので、上から順に見れば足りる。
 */
