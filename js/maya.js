/*
 * マヤ暦。天文計算はいっさい要らず、日数の引き算と割り算だけで出る。
 *
 * 流儀が2つあり、同じ日でも答えが違うので両方出す。
 *
 *   ドリームスペル … 1987年にホゼ・アグエイアスが公開した現代版。日本で「マヤ暦占い」
 *                    として広まっているのはほぼこちら。KIN1〜260。
 *                    【2月29日を数に入れない】のが最大の特徴で、うるう年のたびに
 *                    伝統マヤとのずれが1日ずつ広がっていく。
 *   伝統マヤ       … 遺跡の碑文から復元された本来の暦。ツォルキン260日・ハアブ365日・
 *                    長期暦の3本立て。日数は一度も途切れずに続いている。
 *
 * 検証:
 *   ドリームスペル … 1987-07-26=KIN34(基準) / 1974-08-19=KIN253 / 1986-10-26=KIN21 /
 *                    1990-01-01=KIN143。公開されている計算例と一致
 *   伝統マヤ       … 2012-12-21 → 長期暦 13.0.0.0.0、4アハウ 3カンキン。文献の値と一致
 *
 * astro.js(jdn) に依存する。
 */

